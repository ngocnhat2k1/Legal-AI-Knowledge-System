/**
 * HS classification measured against the company's own cleared declarations.
 *
 * Scored at the 4-DIGIT heading, not the 8-digit line, and that is deliberate: every
 * golden row carries `confidence: uncertain` (TASK-001 — cleared, never certified), so
 * agreement at the leaf would be measuring agreement with a decision nobody stands
 * behind. The heading is where the classification argument actually lives, and it is
 * the level R2 says a candidate list must start at.
 *
 * What this exercises TODAY is the deterministic candidate path — `/tariff/search` over
 * the nomenclature, with the same phrase-then-words fallback the bot uses. It does not
 * call the model, so it is fast, reproducible, and runnable with the model layer off.
 * M4 replaces what sits behind this call; this number is the "before".
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

export interface HsMetrics {
  cases: number;
  top1: number;
  top3: number;
  /** Cases where the deterministic search returned no candidate at all. */
  empty: number;
  misses: string[];
}

interface SearchCandidate {
  hs: string;
  hsDotted: string;
  path: string;
}

interface GoldenCase {
  id: string;
  goods: string;
  hs: string;
}

/**
 * cases.yaml holds one flat mapping per case, and only three fields matter here.
 * Read them directly rather than adding a YAML dependency for three keys — the file
 * is generated by this repo and its shape is fixed (see fixtures/golden-set/README.md).
 */
export function readGoldenCases(text: string): GoldenCase[] {
  const out: GoldenCase[] = [];
  let cur: Partial<GoldenCase> = {};
  let pending: 'goods' | null = null;

  const flush = () => {
    if (cur.id && cur.goods && cur.hs) out.push(cur as GoldenCase);
  };

  for (const raw of text.split('\n')) {
    const line = raw.replace(/\s+$/, '');

    const id = line.match(/^- id:\s*(\S+)/);
    if (id) {
      flush();
      cur = { id: id[1]! };
      pending = null;
      continue;
    }

    const goods = line.match(/^ {2}goods_description:\s*(.*)$/);
    if (goods) {
      cur.goods = goods[1]!.trim();
      pending = 'goods';
      continue;
    }

    const hs = line.match(/^ {2}hs_code:\s*(\S+)/);
    if (hs) {
      cur.hs = hs[1]!.replace(/\D/g, '');
      pending = null;
      continue;
    }

    // A wrapped YAML scalar continues on a deeper-indented line that is not itself a key.
    if (pending === 'goods' && /^ {4}\S/.test(line)) {
      cur.goods = `${cur.goods} ${line.trim()}`;
      continue;
    }
    if (/^ {2}\S/.test(line)) pending = null;
  }
  flush();
  return out;
}

export async function evalHs(apiUrl: string): Promise<HsMetrics> {
  const cases = readGoldenCases(
    readFileSync(join(process.cwd(), 'fixtures', 'golden-set', 'cases.yaml'), 'utf8'),
  );
  const misses: string[] = [];
  let top1 = 0;
  let top3 = 0;
  let empty = 0;

  for (const c of cases) {
    const expected = c.hs.slice(0, 4);
    const groups = await candidateHeadings(apiUrl, c.goods);
    if (!groups.length) empty += 1;
    if (groups[0] === expected) top1 += 1;
    if (groups.slice(0, 3).includes(expected)) top3 += 1;
    else misses.push(`${c.id}: mong nhóm ${expected} — nhận ${groups.slice(0, 3).join('/') || '(rỗng)'}`);
  }

  return {
    cases: cases.length,
    top1: cases.length ? top1 / cases.length : 0,
    top3: cases.length ? top3 / cases.length : 0,
    empty,
    misses,
  };
}

/** Distinct 4-digit headings, in rank order, from the deterministic search path. */
async function candidateHeadings(apiUrl: string, goods: string): Promise<string[]> {
  // A declaration's wording is "<goods name>, <specification, specification…>": the
  // first clause names the thing, the rest describes it. Search the name, then fall
  // back word by word — the same widening the bot does when a phrase finds nothing.
  const head = goods.split(/[,(]/)[0]!.trim().slice(0, 60);
  let rows = await search(apiUrl, head);
  if (!rows.length && /\s/.test(head)) {
    for (const word of head.split(/\s+/).filter((w) => w.length >= 3)) {
      rows = await search(apiUrl, word);
      if (rows.length) break;
    }
  }
  return [...new Set(rows.map((r) => r.hs.slice(0, 4)))];
}

async function search(apiUrl: string, q: string): Promise<SearchCandidate[]> {
  if (q.length < 2) return [];
  try {
    const res = await fetch(`${apiUrl}/tariff/search?q=${encodeURIComponent(q)}`);
    return res.ok ? ((await res.json()) as SearchCandidate[]) : [];
  } catch {
    return [];
  }
}
